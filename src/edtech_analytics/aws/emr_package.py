"""Build the EMR Serverless job artefacts.

* ``job.py``: the entry point (``EntryPoint`` in the Step Functions definition);
* ``edtech_spark.zip``: ``edtech_analytics/spark`` plus the package ``__init__``, passed with
  ``--py-files``. It needs nothing beyond PySpark and the standard library, which the EMR 7.x
  image provides (Python 3.9), so no virtualenv archive is required.

Upload both to ``s3://<code-bucket>/jobs/`` (``make package-emr`` writes them to ``dist/emr``).
"""

from __future__ import annotations

import hashlib
import zipfile
from pathlib import Path

PACKAGE_ROOT = Path(__file__).resolve().parents[1]
ENTRYPOINT = '''"""EMR Serverless entry point (generated by `edtech package-emr`)."""
import sys

from edtech_analytics.spark.job import run

if __name__ == "__main__":
    sys.exit(run())
'''
# Fixed timestamp so the zip is byte-for-byte reproducible.
_ZIP_DATE = (2017, 11, 28, 0, 0, 0)


def build(out_dir: Path) -> dict[str, str]:
    out_dir.mkdir(parents=True, exist_ok=True)
    entry = out_dir / "job.py"
    entry.write_text(ENTRYPOINT, encoding="utf-8")
    archive = out_dir / "edtech_spark.zip"
    files = [PACKAGE_ROOT / "__init__.py", *sorted((PACKAGE_ROOT / "spark").glob("*.py"))]
    with zipfile.ZipFile(archive, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        for path in files:
            arcname = Path("edtech_analytics") / path.relative_to(PACKAGE_ROOT)
            info = zipfile.ZipInfo(arcname.as_posix(), date_time=_ZIP_DATE)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            zf.writestr(info, path.read_bytes())
    return {str(p): hashlib.sha256(p.read_bytes()).hexdigest() for p in (entry, archive)}
